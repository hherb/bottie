//! Portable attachment and generated-image payloads embedded only inside Bottie SQLite backups.

use std::{fs, path::Path};

use rusqlite::{Connection, OpenFlags, params};

use super::StorageError;

mod validation;

use validation::verify_bytes;
pub(super) use validation::{PayloadFault, validate_portable_payload};

const PORTABLE_BACKUP_FORMAT: &str = "bottie-portable-backup";
const LEGACY_PORTABLE_BACKUP_VERSION: i64 = 1;
const PORTABLE_BACKUP_VERSION: i64 = 2;
const MANIFEST_TABLE: &str = "bottie_portable_manifest";
const ATTACHMENT_TABLE: &str = "bottie_portable_attachment_blobs";
const DERIVATIVE_TABLE: &str = "bottie_portable_image_derivatives";
const GENERATED_ASSET_TABLE: &str = "bottie_portable_generated_asset_blobs";
const BLOB_DIRECTORY: &str = "blobs";
const NORMALIZED_DIRECTORY: &str = "normalized-images";
const GENERATED_BLOB_DIRECTORY: &str = "blobs";

/// Catalog files a backup left out, split so a damaged file (possible disk failure) reads apart
/// from a missing one (perhaps quarantined, or never restored) (#267).
#[derive(Debug, Default, Clone, Copy, PartialEq, Eq)]
pub(crate) struct SkippedFiles {
    /// Files absent from disk.
    pub(crate) missing: usize,
    /// Files whose size or SHA-256 no longer matches the catalog.
    pub(crate) damaged: usize,
}

impl SkippedFiles {
    /// Every file left out, whatever the reason.
    pub(crate) fn total(self) -> usize {
        self.missing + self.damaged
    }

    /// Fails unless the snapshot omits exactly the files this backup skipped. `omitted` comes from
    /// `omitted_file_count`, so any other row the snapshot lacks was lost in the payload copy.
    pub(super) fn check_omitted(self, omitted: usize) -> Result<(), StorageError> {
        if omitted == self.total() {
            Ok(())
        } else {
            Err(StorageError::backup_because(
                "the snapshot left out files the backup did not skip",
            ))
        }
    }
}

/// Adds verified attachment, derivative, and generated bytes to an independently copied snapshot.
///
/// Returns how many catalog files were left out because they are absent from disk or fail their
/// checksum. Neither may block every backup (#265); the bytes survive in older snapshots, which
/// automatic rotation holds back.
pub(super) fn embed_portable_payload(
    database: &Path,
    attachment_root: &Path,
    generated_asset_root: &Path,
) -> Result<SkippedFiles, StorageError> {
    let mut connection = Connection::open(database).map_err(StorageError::backup_sqlite)?;
    connection
        .pragma_update(None, "journal_mode", "DELETE")
        .map_err(StorageError::backup_sqlite)?;
    let attachments = attachment_rows(&connection).map_err(StorageError::backup_sqlite)?;
    let derivatives = derivative_rows(&connection).map_err(StorageError::backup_sqlite)?;
    let generated_assets =
        generated_asset_rows(&connection).map_err(StorageError::backup_sqlite)?;
    let transaction = connection
        .transaction()
        .map_err(StorageError::backup_sqlite)?;
    transaction
        .execute_batch(&format!(
            "DROP TABLE IF EXISTS {MANIFEST_TABLE};
             DROP TABLE IF EXISTS {ATTACHMENT_TABLE};
             DROP TABLE IF EXISTS {DERIVATIVE_TABLE};
             DROP TABLE IF EXISTS {GENERATED_ASSET_TABLE};
             CREATE TABLE {MANIFEST_TABLE} (
                 format TEXT PRIMARY KEY NOT NULL,
                 version INTEGER NOT NULL
             ) STRICT;
             CREATE TABLE {ATTACHMENT_TABLE} (
                 sha256 TEXT PRIMARY KEY NOT NULL,
                 byte_size INTEGER NOT NULL CHECK (byte_size >= 0),
                 content BLOB NOT NULL
             ) STRICT;
             CREATE TABLE {DERIVATIVE_TABLE} (
                 sha256 TEXT PRIMARY KEY NOT NULL,
                 format TEXT NOT NULL CHECK (format IN ('jpeg', 'png')),
                 byte_size INTEGER NOT NULL CHECK (byte_size >= 0),
                 content BLOB NOT NULL
             ) STRICT;
             CREATE TABLE {GENERATED_ASSET_TABLE} (
                 sha256 TEXT PRIMARY KEY NOT NULL,
                 byte_size INTEGER NOT NULL CHECK (byte_size >= 0),
                 content BLOB NOT NULL
             ) STRICT;"
        ))
        .map_err(StorageError::backup_sqlite)?;
    transaction
        .execute(
            &format!("INSERT INTO {MANIFEST_TABLE} (format, version) VALUES (?1, ?2)"),
            params![PORTABLE_BACKUP_FORMAT, PORTABLE_BACKUP_VERSION],
        )
        .map_err(StorageError::backup_sqlite)?;
    let mut skipped = SkippedFiles::default();
    for (sha256, byte_size) in attachments {
        let path = content_path(attachment_root, BLOB_DIRECTORY, &sha256, None)
            .map_err(|_| StorageError::backup())?;
        let Some(bytes) = verified_file(&path, &sha256, byte_size, &mut skipped)? else {
            continue;
        };
        transaction
            .execute(
                &format!(
                    "INSERT INTO {ATTACHMENT_TABLE} (sha256, byte_size, content) VALUES (?1, ?2, ?3)"
                ),
                params![sha256, byte_size, bytes],
            )
            .map_err(StorageError::backup_sqlite)?;
    }
    for (sha256, format, byte_size) in derivatives {
        let path = content_path(
            attachment_root,
            NORMALIZED_DIRECTORY,
            &sha256,
            Some(&format),
        )
        .map_err(|_| StorageError::backup())?;
        let Some(bytes) = verified_file(&path, &sha256, byte_size, &mut skipped)? else {
            continue;
        };
        transaction
            .execute(
                &format!(
                    "INSERT INTO {DERIVATIVE_TABLE} (sha256, format, byte_size, content)
                     VALUES (?1, ?2, ?3, ?4)"
                ),
                params![sha256, format, byte_size, bytes],
            )
            .map_err(StorageError::backup_sqlite)?;
    }
    for (sha256, byte_size) in generated_assets {
        let path = generated_content_path(generated_asset_root, &sha256)
            .map_err(|_| StorageError::backup())?;
        let Some(bytes) = verified_file(&path, &sha256, byte_size, &mut skipped)? else {
            continue;
        };
        transaction
            .execute(
                &format!(
                    "INSERT INTO {GENERATED_ASSET_TABLE} (sha256, byte_size, content)
                     VALUES (?1, ?2, ?3)"
                ),
                params![sha256, byte_size, bytes],
            )
            .map_err(StorageError::backup_sqlite)?;
    }
    transaction.commit().map_err(StorageError::backup_sqlite)?;
    validate_portable_payload(&connection)
        .map(|_| skipped)
        .map_err(|fault| fault.backup_error())
}

/// Counts catalog files a snapshot leaves out because they were missing or damaged at backup.
///
/// Validation already rejects embedded rows without a catalog row, so the difference is exact.
pub(super) fn omitted_file_count(database: &Path) -> Result<usize, PayloadFault> {
    let connection = Connection::open_with_flags(database, OpenFlags::SQLITE_OPEN_READ_ONLY)?;
    // The catalog readers treat a missing table as "no files", so an empty file must not read as complete.
    for table in super::backup::REQUIRED_BACKUP_TABLES {
        if !table_exists(&connection, table)? {
            return Err(PayloadFault::NotBottie);
        }
    }
    let expected = attachment_rows(&connection)?.len()
        + derivative_rows(&connection)?.len()
        + generated_asset_rows(&connection)?.len();
    let mut embedded = 0;
    for table in [ATTACHMENT_TABLE, DERIVATIVE_TABLE, GENERATED_ASSET_TABLE] {
        // A pre-portable snapshot has no payload tables, and a version-1 one no generated-image
        // table, so they embed nothing there. Old catalogs are handled by the row readers (#264).
        if !table_exists(&connection, table)? {
            continue;
        }
        let count: i64 =
            connection.query_row(&format!("SELECT COUNT(*) FROM {table}"), [], |row| {
                row.get(0)
            })?;
        embedded += usize::try_from(count).map_err(|_| PayloadFault::Invalid)?;
    }
    Ok(expected.saturating_sub(embedded))
}

/// Counts catalog files that are absent from the live content roots.
pub(super) fn missing_content_count(
    connection: &Connection,
    attachment_root: &Path,
    generated_asset_root: &Path,
) -> Result<usize, StorageError> {
    let mut paths = Vec::new();
    let invalid = |_| StorageError::invalid_backup();
    for (sha256, _) in attachment_rows(connection).map_err(invalid)? {
        paths.push(content_path(
            attachment_root,
            BLOB_DIRECTORY,
            &sha256,
            None,
        )?);
    }
    for (sha256, format, _) in derivative_rows(connection).map_err(invalid)? {
        paths.push(content_path(
            attachment_root,
            NORMALIZED_DIRECTORY,
            &sha256,
            Some(&format),
        )?);
    }
    for (sha256, _) in generated_asset_rows(connection).map_err(invalid)? {
        paths.push(generated_content_path(generated_asset_root, &sha256)?);
    }
    Ok(paths.iter().filter(|path| !path.is_file()).count())
}

/// Rehydrates a verified portable payload into new application-private content roots.
pub(super) fn extract_portable_payload(
    database: &Path,
    attachment_destination: &Path,
    generated_asset_destination: &Path,
) -> Result<bool, StorageError> {
    let connection = Connection::open_with_flags(database, OpenFlags::SQLITE_OPEN_READ_ONLY)
        .map_err(|_| StorageError::invalid_backup())?;
    if !validate_portable_payload(&connection)? {
        return Ok(false);
    }
    fs::create_dir(attachment_destination).map_err(|_| StorageError::restore())?;
    let result = (|| {
        extract_table(
            &connection,
            ATTACHMENT_TABLE,
            attachment_destination,
            BLOB_DIRECTORY,
            false,
        )?;
        extract_table(
            &connection,
            DERIVATIVE_TABLE,
            attachment_destination,
            NORMALIZED_DIRECTORY,
            true,
        )?;
        if table_exists(&connection, GENERATED_ASSET_TABLE)
            .map_err(|_| StorageError::invalid_backup())?
        {
            fs::create_dir(generated_asset_destination).map_err(|_| StorageError::restore())?;
            extract_generated_assets(&connection, generated_asset_destination)?;
        }
        Ok(true)
    })();
    if result.is_err() {
        let _ = fs::remove_dir_all(attachment_destination);
        let _ = fs::remove_dir_all(generated_asset_destination);
    }
    result
}

/// Removes backup-only payload tables before a staged database becomes the live store.
pub(super) fn strip_portable_payload(database: &Path) -> Result<(), StorageError> {
    let connection = Connection::open(database).map_err(|_| StorageError::restore())?;
    strip_portable_payload_from_connection(&connection)?;
    Ok(())
}

/// Removes backup-only tables through an already open live restore connection.
pub(super) fn strip_portable_payload_from_connection(
    connection: &Connection,
) -> Result<(), StorageError> {
    connection
        .execute_batch(&format!(
            "DROP TABLE IF EXISTS {MANIFEST_TABLE};
             DROP TABLE IF EXISTS {ATTACHMENT_TABLE};
             DROP TABLE IF EXISTS {DERIVATIVE_TABLE};
             DROP TABLE IF EXISTS {GENERATED_ASSET_TABLE};"
        ))
        .map_err(|_| StorageError::restore())?;
    Ok(())
}

// Every catalog table postdates automatic rotation, so a snapshot's schema may lack one. A missing
// table lists no files: an answer for rotation and restore, not a failed check (#264).

/// Loads every retained source identity and exact byte size from the copied schema.
fn attachment_rows(connection: &Connection) -> rusqlite::Result<Vec<(String, i64)>> {
    if !table_exists(connection, "attachments")? {
        return Ok(Vec::new());
    }
    connection
        .prepare("SELECT sha256, byte_size FROM attachments ORDER BY sha256")?
        .query_map([], |row| Ok((row.get(0)?, row.get(1)?)))?
        .collect()
}

/// Loads every ready normalized derivative identity, format, and byte size.
fn derivative_rows(connection: &Connection) -> rusqlite::Result<Vec<(String, String, i64)>> {
    let mut sources = Vec::new();
    if table_exists(connection, "attachment_image_normalizations")? {
        sources.push(
            "SELECT normalized_sha256, format, byte_size
             FROM attachment_image_normalizations WHERE state = 'ready'",
        );
    }
    if table_exists(connection, "generated_asset_sources")? {
        sources.push(
            "SELECT sha256,
                    CASE media_type WHEN 'image/jpeg' THEN 'jpeg' ELSE 'png' END,
                    byte_size
             FROM generated_asset_sources WHERE source_type = 'attachment'",
        );
    }
    if sources.is_empty() {
        return Ok(Vec::new());
    }
    // DISTINCT keeps UNION's de-duplication when only one source exists.
    connection
        .prepare(&format!(
            "SELECT DISTINCT * FROM ({}) ORDER BY 1",
            sources.join(" UNION ")
        ))?
        .query_map([], |row| Ok((row.get(0)?, row.get(1)?, row.get(2)?)))?
        .collect()
}

/// Loads every completed generated PNG identity and exact byte size.
fn generated_asset_rows(connection: &Connection) -> rusqlite::Result<Vec<(String, i64)>> {
    if !table_exists(connection, "generated_assets")? {
        return Ok(Vec::new());
    }
    connection
        .prepare(
            "SELECT DISTINCT sha256, byte_size FROM generated_assets
             WHERE status = 'completed' ORDER BY sha256",
        )?
        .query_map([], |row| Ok((row.get(0)?, row.get(1)?)))?
        .collect()
}

/// Extracts one trusted portable table to deterministic hash-sharded native paths.
fn extract_table(
    connection: &Connection,
    table: &str,
    root: &Path,
    directory: &str,
    has_format: bool,
) -> Result<(), StorageError> {
    let query = if has_format {
        format!("SELECT sha256, format, byte_size, content FROM {table} ORDER BY sha256")
    } else {
        format!("SELECT sha256, NULL, byte_size, content FROM {table} ORDER BY sha256")
    };
    let mut statement = connection
        .prepare(&query)
        .map_err(|_| StorageError::invalid_backup())?;
    let rows = statement
        .query_map([], |row| {
            Ok((
                row.get::<_, String>(0)?,
                row.get::<_, Option<String>>(1)?,
                row.get::<_, i64>(2)?,
                row.get::<_, Vec<u8>>(3)?,
            ))
        })
        .map_err(|_| StorageError::invalid_backup())?;
    for row in rows {
        let (sha256, format, byte_size, bytes) = row.map_err(|_| StorageError::invalid_backup())?;
        verify_bytes(&bytes, &sha256, byte_size)?;
        let path = content_path(root, directory, &sha256, format.as_deref())?;
        let parent = path.parent().ok_or_else(StorageError::restore)?;
        fs::create_dir_all(parent).map_err(|_| StorageError::restore())?;
        fs::write(path, bytes).map_err(|_| StorageError::restore())?;
    }
    Ok(())
}

/// Extracts verified generated PNGs to their fixed hash-sharded content paths.
fn extract_generated_assets(connection: &Connection, root: &Path) -> Result<(), StorageError> {
    let mut statement = connection
        .prepare(&format!(
            "SELECT sha256, byte_size, content FROM {GENERATED_ASSET_TABLE} ORDER BY sha256"
        ))
        .map_err(|_| StorageError::invalid_backup())?;
    let rows = statement
        .query_map([], |row| {
            Ok((
                row.get::<_, String>(0)?,
                row.get::<_, i64>(1)?,
                row.get::<_, Vec<u8>>(2)?,
            ))
        })
        .map_err(|_| StorageError::invalid_backup())?;
    for row in rows {
        let (sha256, byte_size, bytes) = row.map_err(|_| StorageError::invalid_backup())?;
        verify_bytes(&bytes, &sha256, byte_size)?;
        let path = generated_content_path(root, &sha256)?;
        let parent = path.parent().ok_or_else(StorageError::restore)?;
        fs::create_dir_all(parent).map_err(|_| StorageError::restore())?;
        fs::write(path, bytes).map_err(|_| StorageError::restore())?;
    }
    Ok(())
}

/// Reads and verifies one file before embedding it into a backup. `None` means it is absent, or its
/// bytes no longer match the catalog (bit-rot, a truncated write), so it is left out (#265) and
/// counted in `skipped` as missing or damaged (#267).
fn verified_file(
    path: &Path,
    sha256: &str,
    byte_size: i64,
    skipped: &mut SkippedFiles,
) -> Result<Option<Vec<u8>>, StorageError> {
    let bytes = match fs::read(path) {
        Ok(bytes) => bytes,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
            skipped.missing += 1;
            return Ok(None);
        }
        Err(error) => return Err(StorageError::backup_because(error.kind())),
    };
    if verify_bytes(&bytes, sha256, byte_size).is_err() {
        skipped.damaged += 1;
        return Ok(None);
    }
    Ok(Some(bytes))
}

/// Builds one validated hash-sharded source or normalized derivative path.
fn content_path(
    root: &Path,
    directory: &str,
    sha256: &str,
    format: Option<&str>,
) -> Result<std::path::PathBuf, StorageError> {
    if sha256.len() != 64
        || !sha256
            .bytes()
            .all(|byte| byte.is_ascii_digit() || matches!(byte, b'a'..=b'f'))
        || format.is_some_and(|value| !matches!(value, "jpeg" | "png"))
    {
        return Err(StorageError::invalid_backup());
    }
    let file_name = format.map_or_else(|| sha256.to_owned(), |value| format!("{sha256}.{value}"));
    Ok(root.join(directory).join(&sha256[..2]).join(file_name))
}

/// Builds one validated hash-sharded generated PNG path.
fn generated_content_path(root: &Path, sha256: &str) -> Result<std::path::PathBuf, StorageError> {
    let base = content_path(root, GENERATED_BLOB_DIRECTORY, sha256, None)?;
    Ok(base.with_file_name(format!("{sha256}.png")))
}

/// Checks one exact SQLite table name without accepting views or similarly named objects.
fn table_exists(connection: &Connection, table: &str) -> rusqlite::Result<bool> {
    connection.query_row(
        "SELECT EXISTS (SELECT 1 FROM sqlite_schema WHERE type = 'table' AND name = ?1)",
        [table],
        |row| row.get(0),
    )
}
